import io
import os

ROOT = "research/protocol/bluetooth_rfcomm"


def sub(path, pairs):
    p = os.path.join(ROOT, path)
    s = io.open(p, encoding="utf-8").read()
    for a, b in pairs:
        if a not in s:
            print("MISS", path, "|", a[:60].replace("\n", " "))
            continue
        s = s.replace(a, b)
    io.open(p, "w", encoding="utf-8").write(s)


